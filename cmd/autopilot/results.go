package main

import (
	"fmt"
	"math"
	"sort"
	"strings"
	"time"

	"github.com/singha105/iam-autopilot/internal/store"
)

// Totals are the headline numbers of docs/results.md. Every value is computed
// from the rollout records (and PR merge times from GitHub), never typed.
type Totals struct {
	Rollouts            int
	RolesTightened      int
	PermissionsBefore   int
	PermissionsAfter    int
	PermissionsRemoved  int
	RemovedPercent      float64
	Rollbacks           int
	MedianDetectSeconds float64
	MedianRollbackSecs  float64
	BreakingLeftInPlace int
}

// computeTotals: a role counts as tightened if it has an ENFORCED rollout; its
// newest ENFORCED rollout gives its before/after counts. A breaking change
// left in place is an ENFORCED rollout that recorded a detection or a denial.
func computeTotals(all []store.Rollout) Totals {
	t := Totals{Rollouts: len(all)}
	latest := map[string]store.Rollout{}
	var detect, rollback []float64
	for _, r := range all {
		switch r.Status {
		case store.StatusEnforced:
			if cur, ok := latest[r.RoleName]; !ok || r.CreatedAt > cur.CreatedAt {
				latest[r.RoleName] = r
			}
			if r.DetectedAt != "" || len(r.Metrics.DeniedActions) > 0 {
				t.BreakingLeftInPlace++
			}
		case store.StatusRolledBack:
			t.Rollbacks++
			detect = append(detect, r.Metrics.DetectSeconds)
			rollback = append(rollback, r.Metrics.RollbackSeconds)
		}
	}
	t.RolesTightened = len(latest)
	for _, r := range latest {
		t.PermissionsBefore += r.Metrics.GrantedBefore
		t.PermissionsAfter += r.Metrics.GrantedAfter
	}
	t.PermissionsRemoved = t.PermissionsBefore - t.PermissionsAfter
	if t.PermissionsBefore > 0 {
		t.RemovedPercent = math.Round(float64(t.PermissionsRemoved)*1000/float64(t.PermissionsBefore)) / 10
	}
	t.MedianDetectSeconds = median(detect)
	t.MedianRollbackSecs = median(rollback)
	return t
}

func median(xs []float64) float64 {
	if len(xs) == 0 {
		return 0
	}
	s := append([]float64{}, xs...)
	sort.Float64s(s)
	if n := len(s); n%2 == 1 {
		return s[n/2]
	} else {
		return (s[n/2-1] + s[n/2]) / 2
	}
}

// renderResults writes docs/results.md. mergedAt maps PR numbers to their
// GitHub merge time (absent for unmerged PRs).
func renderResults(all []store.Rollout, mergedAt map[int]time.Time, generated time.Time, repoURL string) string {
	rows := append([]store.Rollout{}, all...)
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].CreatedAt != rows[j].CreatedAt {
			return rows[i].CreatedAt > rows[j].CreatedAt
		}
		return rows[i].RolloutID > rows[j].RolloutID
	})
	t := computeTotals(rows)
	var b strings.Builder
	b.WriteString("# Results\n\n")
	fmt.Fprintf(&b, "Generated by `autopilot report` from the `iamap-rollouts` DynamoDB table on %s. Do not edit by hand: every number below is computed from the rollout records (merge times from the GitHub API).\n\n", generated.UTC().Format("2006-01-02 15:04 UTC"))

	b.WriteString("## Totals\n\n| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| Roles tightened | %d |\n", t.RolesTightened)
	fmt.Fprintf(&b, "| Permissions granted before → after (latest enforced rollout per role) | %d → %d |\n", t.PermissionsBefore, t.PermissionsAfter)
	fmt.Fprintf(&b, "| Permissions removed | %d (%.1f%%) |\n", t.PermissionsRemoved, t.RemovedPercent)
	fmt.Fprintf(&b, "| Automatic rollbacks | %d |\n", t.Rollbacks)
	if t.Rollbacks > 0 {
		fmt.Fprintf(&b, "| Median time to detect (enforcement → first watch that saw the breakage) | %s |\n", secs(t.MedianDetectSeconds))
		fmt.Fprintf(&b, "| Median time to roll back (detection → previous version restored) | %s |\n", secs(t.MedianRollbackSecs))
	}
	fmt.Fprintf(&b, "| Breaking changes left in place | %d |\n", t.BreakingLeftInPlace)
	fmt.Fprintf(&b, "| Rollout records | %d |\n\n", t.Rollouts)

	b.WriteString("## Every rollout (newest first)\n\n")
	b.WriteString("| Role | Status | Permissions before → after | Removed | Observed actions | Shadow tested / denied | Merge → enforced | Detect | Roll back | PR |\n")
	b.WriteString("|---|---|---|---:|---:|---|---:|---:|---:|---|\n")
	for _, r := range rows {
		m := r.Metrics
		perm, removed, observed, shadowCol := "-", "-", "-", "-"
		if m.GrantedBefore > 0 {
			perm = fmt.Sprintf("%d → %d", m.GrantedBefore, m.GrantedAfter)
			removed = fmt.Sprintf("%.1f%%", m.RemovedPercent)
			observed = fmt.Sprint(m.ObservedActions)
			shadowCol = fmt.Sprintf("%d / %d", m.ShadowTested, m.ShadowDenied)
		}
		mergeToEnforced := "-"
		if merged, ok := mergedAt[r.PRNumber]; ok && r.EnforcedAt != "" {
			if enforced, err := time.Parse(time.RFC3339, r.EnforcedAt); err == nil {
				mergeToEnforced = secs(enforced.Sub(merged).Seconds())
			}
		}
		detect, rb := "-", "-"
		if r.DetectedAt != "" {
			detect = secs(m.DetectSeconds)
		}
		if r.RolledBackAt != "" {
			rb = secs(m.RollbackSeconds)
		}
		pr := "-"
		if r.PRNumber > 0 {
			pr = fmt.Sprintf("[#%d](%s/pull/%d)", r.PRNumber, repoURL, r.PRNumber)
		}
		role := strings.TrimSuffix(strings.TrimPrefix(r.RoleName, "iamap-demo-"), "-role")
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", role, r.Status, perm, removed, observed, shadowCol, mergeToEnforced, detect, rb, pr)
	}
	b.WriteString("\nDetect time is measured from enforcement to the first watch iteration that saw the breakage; the watch polls every `pollSeconds` (300 s), so it is at most one interval after the failing call. Merge → enforced includes the GitHub Actions job that calls the approver.\n")
	return b.String()
}

func secs(s float64) string {
	switch {
	case s < 10:
		return fmt.Sprintf("%.1f s", s)
	case s < 120:
		return fmt.Sprintf("%.0f s", s)
	default:
		return fmt.Sprintf("%.0f s (%.1f min)", s, s/60)
	}
}
